import Database from 'better-sqlite3';
import { afterEach, expect, it, vi } from 'vitest';
import { NextRequest } from 'next/server';
const mock = vi.hoisted(() => ({ db: null as Database.Database | null }));
vi.mock('@/lib/session', () => ({ requireAdmin: vi.fn(async () => ({ id: 'admin' })) }));
vi.mock('@/lib/promotion-repository', () => ({ withPromotionRepository: (action: (repo: null, db: Database.Database) => unknown) => action(null, mock.db!) }));
import { GET } from '@/app/api/admin/promotions/products/route';
afterEach(() => { mock.db?.close(); mock.db = null; });
it('prioritizes a matching variant before exhausting the total result budget', async () => {
  mock.db = new Database(':memory:');
  mock.db.exec(`CREATE TABLE Product (id TEXT PRIMARY KEY,name TEXT,catalogNumber TEXT,hazardous INTEGER,deletedAt TEXT);
    CREATE TABLE ProductVariant (id TEXT PRIMARY KEY,productId TEXT,catalogNumber TEXT,spec TEXT);
    INSERT INTO Product VALUES ('a','TARGET group','A',0,NULL),('b','other','B',0,NULL);
    INSERT INTO ProductVariant VALUES ('target','b','TARGET','target spec'),('a-match','a','A-match','contains TARGET');`);
  const insert = mock.db.prepare('INSERT INTO ProductVariant VALUES (?, ?, ?, ?)');
  mock.db.transaction(() => { for (let i = 0; i < 1999; i++) insert.run(`a${i}`, 'a', `A-${i}`, 'ordinary'); })();
  const response = await GET(new NextRequest('http://localhost/api/admin/promotions/products?search=TARGET'));
  const { products } = await response.json();
  expect(products[0].id).toBe('b');
  expect(products[0].variants[0].id).toBe('target');
  expect(products[1].variants.some((variant: { id: string }) => variant.id === 'a-match')).toBe(true);
  expect(products[1].variantsTruncated).toBe(true);
  expect(products.reduce((sum: number, p: { variants: unknown[] }) => sum + p.variants.length, 0)).toBe(2000);
});
it('returns additional matching products with an explicit offset', async () => {
  mock.db = new Database(':memory:');
  mock.db.exec(`CREATE TABLE Product (id TEXT PRIMARY KEY,name TEXT,catalogNumber TEXT,hazardous INTEGER,deletedAt TEXT);
    CREATE TABLE ProductVariant (id TEXT PRIMARY KEY,productId TEXT,catalogNumber TEXT,spec TEXT);`);
  const insert = mock.db.prepare('INSERT INTO Product VALUES (?, ?, ?, 0, NULL)');
  mock.db.transaction(() => { for (let i = 0; i < 26; i++) insert.run(`p${i}`, 'matching name', `c${String(i).padStart(2, '0')}`); })();
  const first = await GET(new NextRequest('http://localhost/api/admin/promotions/products?search=matching'));
  const second = await GET(new NextRequest('http://localhost/api/admin/promotions/products?search=matching&offset=25'));
  const a = await first.json(); const b = await second.json();
  expect(a.products).toHaveLength(25); expect(a.hasMore).toBe(true);
  expect(b.products).toHaveLength(1); expect(b.hasMore).toBe(false);
  expect(a.products.some((p: { id: string }) => p.id === b.products[0].id)).toBe(false);
});
it('can reload all variants for a product omitted by the global budget', async () => {
  mock.db = new Database(':memory:');
  mock.db.exec(`CREATE TABLE Product (id TEXT PRIMARY KEY,name TEXT,catalogNumber TEXT,hazardous INTEGER,deletedAt TEXT);
    CREATE TABLE ProductVariant (id TEXT PRIMARY KEY,productId TEXT,catalogNumber TEXT,spec TEXT);
    INSERT INTO Product VALUES ('p1','item','P',0,NULL),('hidden','hidden','H',1,NULL);
    INSERT INTO ProductVariant VALUES ('v1','p1','V1','small'),('v2','p1','V2','large');`);
  const response = await GET(new NextRequest('http://localhost/api/admin/promotions/products?productId=p1'));
  const data = await response.json();
  expect(data.variants.map((item: { id: string }) => item.id)).toEqual(['v1', 'v2']);
  expect(data.variantsTruncated).toBe(false);
  expect((await GET(new NextRequest('http://localhost/api/admin/promotions/products?productId=hidden'))).status).toBe(404);
});
