#!/usr/bin/env node
/**
 * Download favicons for scene analysisSoftware + site-recommended tools
 * into public/images/tool-favicons/<hostname>.png, then regenerate
 * src/lib/tool-favicon.ts host list.
 */
import { mkdir, writeFile, readdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const OUT_DIR = path.join(ROOT, 'public/images/tool-favicons');
const HELPER_PATH = path.join(ROOT, 'src/lib/tool-favicon.ts');

async function loadHosts() {
  const scenesUrl = pathToFileURL(path.join(ROOT, 'src/data/scenes.ts')).href;
  const { scenes } = await import(scenesUrl);

  const extras = [
    { href: 'https://mole.fit/?atp=libereal', iconUrl: 'https://mole.fit/img/favicon-mole-192.png' },
  ];

  const byHost = new Map();
  for (const scene of scenes) {
    for (const tool of scene.analysisSoftware ?? []) {
      if (!/^https?:\/\//.test(tool.href)) continue;
      const host = new URL(tool.href).hostname;
      const prev = byHost.get(host);
      byHost.set(host, {
        host,
        iconUrl: tool.iconUrl ?? prev?.iconUrl ?? null,
      });
    }
  }
  for (const tool of extras) {
    const host = new URL(tool.href).hostname;
    byHost.set(host, { host, iconUrl: tool.iconUrl });
  }
  return [...byHost.values()].sort((a, b) => a.host.localeCompare(b.host));
}

async function fetchBytes(url, timeoutMs = 10000) {
  const res = await fetch(url, {
    headers: {
      'user-agent': 'Mozilla/5.0 (compatible; LiberealFaviconCache/1.0)',
      accept: 'image/avif,image/webp,image/apng,image/*,*/*;q=0.8',
    },
    redirect: 'follow',
    signal: AbortSignal.timeout(timeoutMs),
  });
  if (!res.ok) throw new Error(`${res.status}`);
  const buf = Buffer.from(await res.arrayBuffer());
  if (buf.length < 50) throw new Error(`too small ${buf.length}`);
  const head = buf.subarray(0, 32).toString('utf8').toLowerCase();
  if (head.includes('<!doctype') || head.includes('<html')) {
    throw new Error('html body');
  }
  return buf;
}

function candidates(host, iconUrl) {
  const bare = host.startsWith('www.') ? host.slice(4) : host;
  const list = [];
  if (iconUrl) list.push(iconUrl);
  list.push(`https://icons.duckduckgo.com/ip3/${host}.ico`);
  if (bare !== host) list.push(`https://icons.duckduckgo.com/ip3/${bare}.ico`);
  list.push(
    `https://t1.gstatic.com/faviconV2?client=SOCIAL&type=FAVICON&fallback_opts=TYPE,SIZE,URL&url=https://${host}&size=128`,
  );
  list.push(
    `https://t1.gstatic.com/faviconV2?client=SOCIAL&type=FAVICON&fallback_opts=TYPE,SIZE,URL&url=http://${host}&size=128`,
  );
  list.push(`https://${host}/favicon.ico`);
  list.push(`https://${host}/favicon.png`);
  list.push(`https://${host}/apple-touch-icon.png`);
  return list;
}

async function downloadHost({ host, iconUrl }, { force = false } = {}) {
  const dest = path.join(OUT_DIR, `${host}.png`);
  if (!force) {
    try {
      const existing = await readdir(OUT_DIR);
      if (existing.includes(`${host}.png`)) {
        console.log('SKIP', host);
        return true;
      }
    } catch {
      // ignore
    }
  }

  let lastErr;
  for (const url of candidates(host, iconUrl)) {
    try {
      const buf = await fetchBytes(url);
      await writeFile(dest, buf);
      console.log('OK', host, '<-', url, buf.length);
      return true;
    } catch (err) {
      lastErr = err;
    }
  }
  console.error('FAIL', host, lastErr?.message ?? lastErr);
  return false;
}

async function writeHelper() {
  const files = (await readdir(OUT_DIR)).filter((f) => f.endsWith('.png')).sort();
  const hosts = files.map((f) => f.replace(/\.png$/, ''));
  const content = `/** Auto-generated by scripts/cache-tool-favicons.mjs — do not edit by hand. */
export const TOOL_FAVICON_DIR = '/images/tool-favicons';

export const CACHED_TOOL_FAVICON_HOSTS = new Set<string>([
${hosts.map((h) => `  ${JSON.stringify(h)},`).join('\n')}
]);

export function getCachedToolFaviconPath(hostname: string): string | null {
  if (!CACHED_TOOL_FAVICON_HOSTS.has(hostname)) return null;
  return \`\${TOOL_FAVICON_DIR}/\${hostname}.png\`;
}

/** Resolve a tool icon to a same-origin path. Never returns third-party favicon URLs. */
export function getToolFaviconSrc(href: string, iconUrl?: string | null): string | null {
  if (iconUrl && iconUrl.startsWith('/')) return iconUrl;

  if (!href.startsWith('http://') && !href.startsWith('https://')) return null;

  try {
    return getCachedToolFaviconPath(new URL(href).hostname);
  } catch {
    return null;
  }
}
`;
  await writeFile(HELPER_PATH, content);
  console.log(`wrote ${HELPER_PATH} (${hosts.length} hosts)`);
}

const force = process.argv.includes('--force');
const regenerateOnly = process.argv.includes('--regenerate-only');
await mkdir(OUT_DIR, { recursive: true });

if (!regenerateOnly) {
  const hosts = await loadHosts();
  let ok = 0;
  for (const item of hosts) {
    if (await downloadHost(item, { force })) ok += 1;
  }
  console.log(`done ${ok}/${hosts.length}`);
  if (ok < hosts.length) process.exitCode = 1;
}

await writeHelper();
